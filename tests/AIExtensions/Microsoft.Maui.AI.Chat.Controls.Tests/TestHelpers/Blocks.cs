using System.Collections.ObjectModel;

namespace Microsoft.Maui.AI.Chat.Controls.Tests.TestHelpers;

/// <summary>Builds engine blocks directly, for view and template tests that need no session.</summary>
internal static class Blocks
{
    public static TextContentBlock Text(string text, ChatRole? role = null)
    {
        var block = new TextContentBlock { Role = role ?? ChatRole.Assistant };
        block.AppendText(text);
        return block;
    }

    public static FunctionInvocationContentBlock ToolCall(
        string name,
        IDictionary<string, object?>? arguments = null,
        object? result = null,
        Exception? exception = null)
    {
        var block = new FunctionInvocationContentBlock
        {
            Call = new FunctionCallContent("call-1", name, arguments),
            Role = ChatRole.Assistant,
        };
        if (result is not null || exception is not null)
            block.Result = new FunctionResultContent("call-1", result) { Exception = exception };
        return block;
    }

    public static ToolApprovalBlock Approval(string name, IDictionary<string, object?>? arguments = null)
    {
        var inner = ToolCall(name, arguments);
        var request = new ToolApprovalRequestContent("approval-1", inner.Call!);
        return new ToolApprovalBlock(inner, request) { Role = ChatRole.Assistant };
    }

    public static UIActionBlock UIAction(string name, UIActionInvocationMode mode, Func<string>? action = null)
    {
        var function = AIFunctionFactory.Create(action ?? (() => "done"), name);
        var inner = ToolCall(name);
        return new UIActionBlock(function, mode, inner, services: null) { Role = ChatRole.Assistant };
    }

    public static ReasoningContentBlock Reasoning(string? text, string? protectedData = null)
    {
        var block = new ReasoningContentBlock { ProtectedData = protectedData, Role = ChatRole.Assistant };
        if (text is not null)
            block.AppendText(text);
        return block;
    }

    public static MediaContentBlock Media(AIContent content) => new(content) { Role = ChatRole.Assistant };

    public static DataContent Png(string name = "image.png") => new(new byte[] { 137, 80, 78, 71 }, "image/png") { Name = name };

    public static DataContent Pdf(string name = "report.pdf", int bytes = 2048) => new(new byte[bytes], "application/pdf") { Name = name };
}

