    /// <summary>
    /// The digest covers flow content, so an edit since the run legitimately stops the identity
    /// resolving. That is information, not an error to smooth over: the sidecar still records the
    /// digest the flow had when it last ran, which names the test while stating plainly that this
    /// checkout cannot reproduce it.
    /// </summary>
    [Fact]
    public async Task FlowIdentity_Resolve_WithAFlowEditedSinceTheRun_ReportsSupersededNotAMatch()
    {
        var directory = CreateDirectory("resolve-superseded");
        var flowPath = await WriteFlowAsync(directory, "checkout", "Alpha");
        var identity = await ComputeIdentityAsync(directory, "checkout", "android");
        var recorded = await ComputeFlowDigestAsync(directory, "checkout");
        await WritePlanAsync(directory, "checkout", recorded);
        await WriteFlowAsync(directory, "checkout", "Gamma");
        var current = await ComputeFlowDigestAsync(directory, "checkout");
        Assert.NotEqual(recorded, current);
        var cli = new CliTestHarness(mockAgentPort: 1);

        var result = await cli.InvokeRawAsync(
            "devflow", "flow", "identity", "--resolve", identity, "--search", directory, "--platform", "android", "--json");

        // The working tree does not reproduce the run, so a scripted consumer must not read this
        // as success even though the test has been named.
        Assert.Equal(1, result.ExitCode);
        var root = result.ParseJsonOutput();
        Assert.False(root.GetProperty("ok").GetBoolean());
        var resolve = root.GetProperty("resolve");
        Assert.Equal("matched-superseded", resolve.GetProperty("outcome").GetString());
        var match = Assert.Single(resolve.GetProperty("matches").EnumerateArray().ToList());
        Assert.Equal("checkout.md", match.GetProperty("path").GetString());
        Assert.Equal("plan-sidecar", match.GetProperty("source").GetString());
        Assert.Equal(recorded, match.GetProperty("flowDigest").GetString());
        Assert.Equal(current, match.GetProperty("currentFlowDigest").GetString());
        Assert.False(match.GetProperty("planBindingCurrent").GetBoolean());
        var explanation = string.Join(" ", resolve.GetProperty("explanation").EnumerateArray().Select(item => item.GetString()));
        Assert.Contains("has been edited since the run", explanation, StringComparison.Ordinal);
        Assert.Contains("Check out the commit named in the issue", explanation, StringComparison.Ordinal);
        Assert.True(File.Exists(flowPath));
    }

    /// <summary>
    /// A superseded match rests on the sidecar having been bound to this flow at run time, which
    /// <c>CommittedFlowBundleLoader</c> enforces on both <c>flow.path</c> and <c>flow.digest</c>. A
    /// sidecar copy-pasted from another flow could never have run, so honouring its digest would
    /// name a flow that did not produce the identity - the worst answer this command could give.
    /// </summary>
    [Fact]
    public async Task FlowIdentity_Resolve_WithASidecarBoundToAnotherFlow_ReportsNoMatchNotSuperseded()
    {
        var directory = CreateDirectory("resolve-foreign-sidecar");
        await WriteFlowAsync(directory, "checkout", "Alpha");
        var identity = await ComputeIdentityAsync(directory, "checkout", "android");
        var recorded = await ComputeFlowDigestAsync(directory, "checkout");
        await WriteFlowAsync(directory, "checkout", "Gamma");

        // 'search.md' never had 'checkout.md's digest; its sidecar merely claims it.
        await WriteFlowAsync(directory, "search", "Beta");
        await WritePlanAsync(directory, "search", recorded, boundPath: "checkout.md");
        var cli = new CliTestHarness(mockAgentPort: 1);

        var result = await cli.InvokeRawAsync(
            "devflow", "flow", "identity", "--resolve", identity, "--search", directory, "--platform", "android", "--json");

        Assert.Equal(1, result.ExitCode);
        var resolve = result.ParseJsonOutput().GetProperty("resolve");
        Assert.Equal("no-match", resolve.GetProperty("outcome").GetString());
        Assert.Empty(resolve.GetProperty("matches").EnumerateArray());
    }

