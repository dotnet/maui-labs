    [Theory]
    [MemberData(nameof(ProducerVectors))]
    public void ComputeTestIdentity_ReproducesTheProducerDigest(
        string platform, string tier, string flowDigest, string expected)
    {
        Assert.Equal(expected, FlowIdentityCommands.ComputeTestIdentity(platform, tier, flowDigest));

        // The producer is handed the manifest digest verbatim, and its Test-Sha256 guard pins that
        // to the sha256:-prefixed form. Accepting the bare hex a caller gets from ComputeFlowDigest
        // has to reach the same digest, or the resolver would never match a real flow.
        Assert.Equal(expected, FlowIdentityCommands.ComputeTestIdentity(platform, tier, flowDigest[7..]));
    }

    /// <summary>
    /// The PowerShell <c>`n</c> escape is LF. Using <see cref="Environment.NewLine"/> on Windows
    /// would emit CRLF and silently produce a digest that can never match a published issue, so the
    /// difference is asserted rather than assumed.
    /// </summary>
    [Fact]
    public void ComputeTestIdentity_UsesLineFeedSeparatorsNotTheEnvironmentNewline()
    {
        const string Platform = "android";
        const string Tier = "tier-1";
        const string FlowDigest = "sha256:d29ef0c7ba89c338c3ae58f079b92e8c4ac8ed0ca161a57b68724def8195fd56";

        var identity = FlowIdentityCommands.ComputeTestIdentity(Platform, Tier, FlowDigest);
        Assert.Equal(Sha256Text($"devflow-ci-test-identity-v1\n{Platform}\n{Tier}\n{FlowDigest}"), identity);
        Assert.NotEqual(Sha256Text($"devflow-ci-test-identity-v1\r\n{Platform}\r\n{Tier}\r\n{FlowDigest}"), identity);
    }

    /// <summary>
    /// Round-trips against the committed producer itself. The three hashing functions are lifted
    /// out of <c>New-DevFlowFailureHandoff.ps1</c> by its own parser, so this asserts parity with
    /// the exact text CI runs rather than with a copy of it.
    /// </summary>
    [Theory]
    [MemberData(nameof(ProducerVectors))]
    public async Task ComputeTestIdentity_MatchesTheCommittedPowerShellProducer(
        string platform, string tier, string flowDigest, string expected)
    {
        var script = Path.Combine(FindRepositoryRoot(), "eng", "devflow", "New-DevFlowFailureHandoff.ps1");
        Assert.True(File.Exists(script), $"The producer script was not found at '{script}'.");

        var produced = await RunProducerIdentityAsync(script, platform, tier, flowDigest);
        if (produced is null)
        {
            // xUnit v2.9.3 has no dynamic skip. CI runs this suite on windows-latest and
            // macos-latest, both of which ship pwsh, so a null here on Windows means the producer
            // harness broke rather than that pwsh is genuinely absent - fail instead of going quiet.
            Assert.False(OperatingSystem.IsWindows(), "pwsh was expected to be available on Windows.");
            return; // pwsh is not installed; the pinned vectors still guard the construction
        }

        Assert.Equal(expected, produced);
        Assert.Equal(produced, FlowIdentityCommands.ComputeTestIdentity(platform, tier, flowDigest));
    }

