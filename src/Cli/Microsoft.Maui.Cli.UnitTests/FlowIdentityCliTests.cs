    private string CreateDirectory(string name)
    {
        var directory = Path.Combine(_root, name);
        Directory.CreateDirectory(directory);
        return directory;
    }

    private static async Task<string> WriteFlowAsync(string directory, string name, string automationId)
    {
        var path = Path.Combine(directory, name + ".md");
        var markdown = $$"""
        # Scenario: {{name}}

        ```json maui-test
        {
          "schema": 2,
          "name": "{{name}}",
          "app": "com.example.identityfixture",
          "platform": "android",
          "steps": [
            {
              "seq": 1,
              "action": "tap",
              "args": { "selector": { "automationId": "{{automationId}}" } }
            }
          ]
        }
        ```
        """;
        await File.WriteAllTextAsync(path, markdown);
        return path;
    }

    private static async Task WritePlanAsync(
        string directory,
        string name,
        string flowDigest,
        string? boundPath = null)
    {
        var path = Path.Combine(directory, name + ".maui-plan.json");
        var json = $$"""
        {
          "schema": 1,
          "planId": "plan-{{name}}",
          "revision": 1,
          "flow": {
            "path": "{{boundPath ?? name + ".md"}}",
            "digest": "{{flowDigest[7..]}}"
          },
          "title": "{{name}}",
          "goal": "Replay the committed {{name}} flow.",
          "sideEffectPolicy": "none"
        }
        """;
        await File.WriteAllTextAsync(path, json);
    }

    private static async Task<string> ComputeFlowDigestAsync(string directory, string name)
    {
        var result = await FlowIdentityCommands.ExecuteAsync(
            Path.Combine(directory, name + ".md"), resolve: null, search: null, platform: "android", tier: "tier-1");
        return Assert.Single(result.Flows).FlowDigest;
    }

    private static async Task<string> ComputeIdentityAsync(string directory, string name, string platform)
        => FlowIdentityCommands.ComputeTestIdentity(platform, "tier-1", await ComputeFlowDigestAsync(directory, name));

    private static string Sha256Text(string text)
        => "sha256:" + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text))).ToLowerInvariant();

    private static List<string> Snapshot(string directory)
        => Directory.GetFiles(directory, "*", SearchOption.AllDirectories)
            .OrderBy(static path => path, StringComparer.Ordinal)
            .Select(static path =>
                $"{Path.GetFileName(path)}:{Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path)))}")
            .ToList();

    /// <summary>
    /// Lifts the producer's own hashing functions out of the committed script with the PowerShell
    /// parser and calls <c>Get-TestIdentity</c>, so the assertion is against the exact text CI
    /// runs. Returns null when pwsh is unavailable.
    /// </summary>
    private async Task<string?> RunProducerIdentityAsync(
        string script, string platform, string tier, string flowDigest)
    {
        // Driven through -File rather than -Command: -Command re-parses the joined argument
        // tokens, which mangles a multi-line harness before PowerShell ever runs it.
        var harnessPath = Path.Combine(_root, "producer-identity-harness.ps1");
        if (!File.Exists(harnessPath))
        {
            await File.WriteAllTextAsync(harnessPath, """
                param(
                    [Parameter(Mandatory)] [string] $ScriptPath,
                    [Parameter(Mandatory)] [string] $Platform,
                    [Parameter(Mandatory)] [string] $Tier,
                    [Parameter(Mandatory)] [string] $FlowDigest
                )

                $tokens = $null
                $errors = $null
                $ast = [System.Management.Automation.Language.Parser]::ParseFile($ScriptPath, [ref] $tokens, [ref] $errors)
                if ($errors -and $errors.Count -gt 0) { throw 'producer-parse-failed' }
                foreach ($name in @('Get-Sha256Bytes', 'Get-Sha256Text', 'Get-TestIdentity')) {
                    $found = $ast.FindAll({
                        param($node)
                        $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq $name
                    }, $true)
                    if ($found.Count -ne 1) { throw "producer-function-missing:$name" }
                    . ([scriptblock]::Create($found[0].Extent.Text))
                }
                Write-Output (Get-TestIdentity -Platform $Platform -Tier $Tier -FlowDigest $FlowDigest)
                """);
        }

        using var process = new Process
        {
            StartInfo = new ProcessStartInfo(OperatingSystem.IsWindows() ? "pwsh.exe" : "pwsh")
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            },
        };
        process.StartInfo.ArgumentList.Add("-NoLogo");
        process.StartInfo.ArgumentList.Add("-NoProfile");
        process.StartInfo.ArgumentList.Add("-File");
        process.StartInfo.ArgumentList.Add(harnessPath);
        process.StartInfo.ArgumentList.Add("-ScriptPath");
        process.StartInfo.ArgumentList.Add(script);
        process.StartInfo.ArgumentList.Add("-Platform");
        process.StartInfo.ArgumentList.Add(platform);
        process.StartInfo.ArgumentList.Add("-Tier");
        process.StartInfo.ArgumentList.Add(tier);
        process.StartInfo.ArgumentList.Add("-FlowDigest");
        process.StartInfo.ArgumentList.Add(flowDigest);

        try
        {
            process.Start();
        }
        catch (Exception ex) when (ex is System.ComponentModel.Win32Exception or PlatformNotSupportedException)
        {
            return null;
        }

        var stdoutTask = process.StandardOutput.ReadToEndAsync();
        var stderrTask = process.StandardError.ReadToEndAsync();
        await Task.WhenAll(stdoutTask, stderrTask);
        var stdout = await stdoutTask;
        var stderr = await stderrTask;
        await process.WaitForExitAsync();
        Assert.True(process.ExitCode == 0, $"The producer harness failed: {stderr}");
        return stdout.Trim();
    }

    private static string FindRepositoryRoot()
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "MauiLabs.slnx")))
                return directory.FullName;
        }
        throw new InvalidOperationException("Repository root was not found.");
    }

    public void Dispose()
    {
        try
        {
            if (Directory.Exists(_root))
                Directory.Delete(_root, recursive: true);
        }
        catch (IOException)
        {
        }
    }
